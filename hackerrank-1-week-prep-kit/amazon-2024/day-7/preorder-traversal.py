class Node:
    def __init__(self, info): 
        self.info = info  
        self.left = None  
        self.right = None 
        self.level = None 

    def __str__(self):
        return str(self.info) 

class BinarySearchTree:
    def __init__(self): 
        self.root = None

    def create(self, val):  
        if self.root == None:
            self.root = Node(val)
        else:
            current = self.root
         
            while True:
                if val < current.info:
                    if current.left:
                        current = current.left
                    else:
                        current.left = Node(val)
                        break
                elif val > current.info:
                    if current.right:
                        current = current.right
                    else:
                        current.right = Node(val)
                        break
                else:
                    break

"""
Node is defined as
self.left (the left child of the node)
self.right (the right child of the node)
self.info (the value of the node)
"""
def preOrderHelper(root, s):
    if root is None:
        return ''
        
    info = str(root.info)
    left = preOrderHelper(root.left, s)
    right = preOrderHelper(root.right, s)
    
    s += ' '.join([info, left, right])
    while '  ' in s:
        s = s.replace('  ', ' ')
    
    return s

def preOrder(root):
    #Write your code here
    print(preOrderHelper(root, ''))



